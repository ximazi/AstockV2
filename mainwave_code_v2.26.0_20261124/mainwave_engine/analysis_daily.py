"""Publish the same analysis contract used by the single-stock visual viewer."""
from __future__ import annotations

import argparse
import hashlib
import json
from collections import Counter
from pathlib import Path

import pandas as pd

from . import analysis_core as AC
from . import market_context as MC
from . import stock_analyzer as SA
from . import price_volume_context as PVC
from .pipeline import _write

DISPLAY_LIMIT = 15


def run(as_of: str) -> dict:
    date = str(pd.Timestamp(as_of).date())
    output = SA.OUT_ROOT / date.replace("-", "")
    # Explain the complete discovery union before applying the display limit.
    source = output / "mainwave_discovery_candidates.csv"
    complete_pool = source.exists()
    if not complete_pool:
        source = output / "mainwave_weekly_candidates.csv"
    candidates = pd.read_csv(source)
    candidates = candidates.drop_duplicates("symbol")
    input_count = len(candidates)
    candidates["tracking_only"] = False
    for folder in sorted(SA.OUT_ROOT.glob("????????"), reverse=True):
        if not folder.name.isdigit() or folder.name >= date.replace("-", ""):
            continue
        prior = SA._read_json(folder / "analysis_evidence.json", {})
        if not prior.get("records"):
            continue
        current_symbols = set(candidates.symbol)
        tracked = [{"symbol": symbol, "tracking_only": True} for symbol, core in prior.get("records", {}).items()
                   if symbol not in current_symbols and core["state_vector"]["phase"] not in {"DECLINE", "REPAIR"}
                   and core.get("observation_mode") != "HISTORICAL_RECONSTRUCTION"]
        retained = current_symbols | {row["symbol"] for row in tracked}
        tracked.extend({"symbol": symbol, "tracking_only": True} for symbol in prior.get("pending_symbols", [])
                       if symbol not in retained)
        candidates = pd.concat([candidates, pd.DataFrame(tracked)], ignore_index=True)
        break
    market = MC.write(date)
    records, errors, evidence = [], [], {}
    for index, item in enumerate(candidates.to_dict("records"), 1):
        symbol = str(item["symbol"])
        print(f"[analysis_daily] [{index}/{len(candidates)}] {symbol}", flush=True)
        try:
            # Compact evidence is archived below; full chart JSON is generated by the single-stock UI on demand.
            data = SA.analyze(symbol, date, persist=False)
            core = data["analysis_core"]
            evidence[symbol] = core
            state, window = core["state_vector"], core["review_window"]
            route = core.get("route_evidence", {})
            records.append({
                "symbol": symbol, "name": data["identity"]["name"],
                "tracking_only": bool(item["tracking_only"]),
                "value_tier": core["advice"], "value_tier_label": core["advice_label"],
                "structural_advice": core["structural_advice"], "structural_advice_label": core["structural_advice_label"],
                "buy_state_label": core["advice_label"], "execution_permission_label": "仅分析建议",
                "belonging_theme": data["theme"]["belonging_theme"],
                "discovery_path_label": data["lifecycle"]["discovery_path_label"],
                "route_ids": route.get("route_ids", ""), "route_status": route.get("status", ""),
                "preparation_id": route.get("preparation_id", ""),
                "preparation_first_seen": route.get("preparation_first_seen", ""),
                "preparation_origin": route.get("preparation_origin", ""),
                "preparation_state": route.get("preparation_state", ""),
                "entry_contract": core["entry_contract"]["contract"],
                "contract_missing": "|".join(core["entry_contract"]["missing"]),
                "local_role": state["local_role"], "location": state["location"],
                "route_bias_atr": route.get("bias_atr"),
                "ignition_at": route.get("attempt_at", ""), "accepted_at": route.get("accepted_at", ""),
                "stock_lifecycle_label": data["lifecycle"]["current_label"],
                "phase_label": state["phase_label"], "active_strategy": core["active_strategy"],
                "setup_status": state["setup_status"], "cycle_id": state["cycle_id"],
                "price_date": data["meta"]["price_date"], "close": data["price"]["close"],
                "ema20_bias_pct": data["price"]["ema20_bias_pct"],
                "review_lower": window["lower"], "review_upper": window["upper"],
                "invalid": window["invalid"], "reason": "；".join(core["reasons"]),
                "next_condition": core["next_condition"], "analysis_version": AC.VERSION,
                "buy_policy_version": core["buy_plan"]["version"],
                "initial_fraction": core["buy_plan"]["initial_fraction"],
                "initial_review": core["buy_plan"]["initial_review"],
                "conditional_add_review": core["buy_plan"]["add_review"],
                "add_observation": core["buy_plan"]["observation"]["status"],
                "buy_plan": core["buy_plan"],
                "sell_policy_version": core["sell_plan"]["version"],
                "sell_status": core["sell_plan"]["status"],
                "sell_status_label": core["sell_plan"]["status_label"],
                "sell_structure_alert": core["sell_plan"]["observation"].get("current_structure_alert", ""),
                "sell_hard_floor": core["sell_plan"]["observation"].get("hard_floor"),
                "sell_soft_floor": core["sell_plan"]["observation"].get("soft_floor"),
                "sell_plan": core["sell_plan"],
                "breakout_status": core["breakout"].get("breakout_status", "NONE"),
                "chain_linked": core["chain_linked"],
                "evidence_change": core["evolution"]["summary"],
                "evidence_previous_date": core["evolution"]["previous_as_of"],
                "price_volume_context": core.get("price_volume_context", {}),
                "price_volume_label": core.get("price_volume_context", {}).get("latest", {}).get("label", "未计算"),
            })
        except (OSError, ValueError, KeyError) as exc:
            errors.append({"symbol": symbol, "error": str(exc)})
            print(f"[analysis_daily] FAILED {symbol}: {exc}", flush=True)
    decision_rows = []
    for symbol, core in evidence.items():
        failed_checks = [c["id"] + ":" + c["status"] for c in core["checks"] if c["status"] != "PASS"]
        decision_rows.append({"symbol": symbol, "as_of": date, "analysis_version": AC.VERSION,
                              "decision": core["advice"], "contract": core["entry_contract"]["contract"],
                              "preparation_id": core["route_evidence"].get("preparation_id", ""),
                              "cycle_id": core["state_vector"]["cycle_id"],
                              "breakout_id": core["breakout"].get("breakout_id", ""),
                              "review_window": core["review_window"],
                              "buy_plan": core["buy_plan"],
                              "sell_plan": core["sell_plan"],
                              "first_nonpass_check": failed_checks[0] if failed_checks else "",
                              "all_nonpass_checks": "|".join(failed_checks),
                              "contract_missing": "|".join(core["entry_contract"]["missing"])})
    pd.DataFrame(decision_rows, columns=["symbol", "as_of", "analysis_version", "decision", "contract",
        "preparation_id", "cycle_id", "breakout_id", "review_window", "buy_plan", "sell_plan", "first_nonpass_check",
        "all_nonpass_checks", "contract_missing"]).to_csv(output / "analysis_decision_funnel.csv", index=False, encoding="utf-8-sig")
    snapshot = {"as_of": date, "analysis_version": AC.VERSION, "market": market,
                "records": decision_rows, "orders_enabled": False,
                "source_hash": hashlib.sha256(source.read_bytes()).hexdigest(),
                "observation_basis": "ASOF_RECONSTRUCTION_NOT_PROOF_OF_ORIGINAL_LIVE_HIT"}
    snapshot_hash = hashlib.sha256(json.dumps(snapshot, sort_keys=True, ensure_ascii=False).encode("utf-8")).hexdigest()
    snapshot_path = output / "decision_snapshots" / f"{snapshot_hash}.json"
    if not snapshot_path.exists():
        _write(snapshot_path, snapshot)
    records.sort(key=lambda r: (r["tracking_only"], AC.ADVICE_ORDER[r["value_tier"]], AC.ADVICE_ORDER[r["structural_advice"]],
                               abs(r["route_bias_atr"]) if r["route_bias_atr"] is not None else float("inf"), r["symbol"]))
    for rank, row in enumerate(records, 1):
        row["value_rank"] = rank
        row["display_selected"] = rank <= DISPLAY_LIMIT and not row["tracking_only"]
        row["display_reason"] = ("离池续踪，等待新候选证据" if row["tracking_only"] else
                                 "进入展示窗口" if rank <= DISPLAY_LIMIT else "展示名额之外，分析与证据保留")
    displayed = [r for r in records if r["display_selected"]]
    summary = {"input_candidates": input_count, "tracked_extra": len(candidates) - input_count,
               "analyzed": len(records), "failed": len(errors),
               "advice_counts": dict(Counter(r["value_tier"] for r in records)),
               "orders_created": 0, "status": "PARTIAL" if errors else "SUCCESS",
               "initial_reviews": sum(r["initial_review"] for r in records),
               "conditional_add_reviews": sum(r["conditional_add_review"] for r in records),
               "sell_reference_counts": dict(Counter(r["sell_status"] for r in records)),
               "price_volume_counts": dict(Counter(r["price_volume_label"] for r in records)),
               "displayed": len(displayed), "full_discovery_pool": complete_pool,
               "input_source": source.name,
               "scope": ("全市场三路径证据池与既有资格池合并分析，完成后才截取展示；本步骤不重复扫描全市场" if complete_pool
                         else "旧日报兼容模式：仅已有展示池，不能声称覆盖截断前候选；需重跑three_direction_report"),
               "ranking": "建议类别优先；同类优先偏离较小、再按代码稳定排序；不是预期收益排名"}
    payload = {"as_of": date, "version": AC.VERSION, "mode": "ANALYSIS_ONLY",
               "market": market, "summary": summary, "records": displayed, "errors": errors}
    _write(output / "analysis_board.json", payload)
    _write(output / "analysis_universe.json", {**payload, "records": records})
    _write(output / "analysis_evidence.json", {"as_of": date, "version": AC.VERSION, "records": evidence,
                                              "pending_symbols": [r["symbol"] for r in errors]})
    frame = pd.DataFrame(records)
    frame.to_csv(output / "analysis_board.csv", index=False, encoding="utf-8-sig")
    pv_rows = [{"symbol": r["symbol"], "name": r["name"], "route_ids": r["route_ids"],
                "production_advice": r["value_tier"], "production_demand": evidence[r["symbol"]]["route_evidence"].get("demand"),
                **r["price_volume_context"].get("latest", {})} for r in records]
    pv_payload = {"as_of": date, "version": PVC.VERSION, "rules": PVC.RULES, "orders_enabled": False,
                  "notice": PVC.NOTICE, "scope": "已合并候选与续踪池，非额外全市场扫描", "records": pv_rows}
    _write(output / "price_volume_observations.json", pv_payload)
    pd.DataFrame(pv_rows).to_csv(output / "price_volume_observations.csv", index=False, encoding="utf-8-sig")
    diagnostics = [{**r, "diagnostic": "ALTERNATIVE_DEMAND_MISSING" if r.get("alternative_demand_evidence") and not r.get("production_demand")
                    else "PRESSURE_REVIEW" if r.get("state") == "SUPPLY_PRESSURE" else "CONTEXT_REVIEW"}
                   for r in pv_rows if r.get("event") or r.get("state") not in {"UNRESOLVED", None}]
    _write(output / "price_volume_diagnostics.json", {**pv_payload, "records": diagnostics,
        "boundary": "待复盘线索，不是已证实漏选/误报；全市场发现能力需另作历史对照。"})
    exit_fields = ["symbol", "name", "sell_status_label", "sell_structure_alert", "sell_hard_floor", "sell_soft_floor", "sell_plan"]
    pd.DataFrame(records, columns=exit_fields).to_csv(output / "analysis_exit_review.csv", index=False, encoding="utf-8-sig")
    exit_alerts = [r for r in records if r["sell_status"] in {"HARD_EXIT_PENDING", "EXIT_NEXT_OPEN", "REDUCE_NEXT_OPEN", "SOFT_CONFIRMING"}
                   or r["sell_structure_alert"]]
    audit = [{"symbol": r["symbol"], "status": "ANALYZED", "advice": r["value_tier"],
              "display_selected": r["display_selected"], "reason": r["display_reason"] + "；" + r["reason"]}
             for r in records]
    audit.extend({"symbol": r["symbol"], "status": "FAILED", "advice": "DATA_WAIT",
                  "display_selected": False, "reason": r["error"]} for r in errors)
    pd.DataFrame(audit, columns=["symbol", "status", "advice", "display_selected", "reason"]).to_csv(
        output / "analysis_candidate_audit.csv", index=False, encoding="utf-8-sig")
    fields = ["value_rank", "symbol", "name", "route_ids", "belonging_theme", "stock_lifecycle_label",
              "active_strategy", "value_tier_label", "price_volume_label", "initial_fraction", "conditional_add_review",
              "review_lower", "review_upper", "invalid", "evidence_change", "next_condition"]
    lines = [f"# 生命周期分析总览 {date}", "", f"- 分析版本：{AC.VERSION}；仅分析，不生成成交。",
             f"- 市场：{market['structure']} / {market['temperature']}；数据：{market['data_status']}。",
             f"- 候选 {len(candidates)}，完成 {len(records)}，失败 {len(errors)}。",
             "- 正式买点：首仓为单标的计划预算50%；7个交易日内回撤3%/6%后缩量测试并再转强，才复核余仓21.43%/28.57%；无机会不补。",
             f"- 首仓复核 {summary['initial_reviews']}；条件补仓复核 {summary['conditional_add_reviews']}（必须另核已有首仓、未补该档、无卖出）。",
             "- 正式卖点：硬底线固定2ATR0；普通回踩收盘确认，强势增加确认空间；成熟量价异常分批保护，结构破坏退出；第20日条件续持，最多60日。",
             f"- {summary['scope']}。", f"- {summary['ranking']}。", "",
             pd.DataFrame(displayed)[fields].to_markdown(index=False) if displayed else "无可展示结果。", "",
              f"- 展示 {summary['displayed']} 只；完整分析见 analysis_universe.json / analysis_board.csv。",
              f"- 量价只读观察：{summary['price_volume_counts']}；不会改变排序、许可或买卖规则。",
              "- 量价观察与待复盘队列：price_volume_observations.csv / price_volume_diagnostics.json；阈值待校准。",
             "- 全候选去向见 analysis_candidate_audit.csv；证据基线见 analysis_evidence.json。", "",
             "## 卖点参考复核", "- 最近合格信号的假设参考周期，不是持仓台账；不得将参考退出当成实际成交。历史已结束参考周期不重复发出今天卖出建议。",
             f"- 当前退出/保护/收盘确认或结构风险参考共 {len(exit_alerts)} 个；完整结果见 analysis_exit_review.csv。",
             pd.DataFrame(exit_alerts[:20])[exit_fields[:-1]].to_markdown(index=False) if exit_alerts else "- 无当前退出参考警报；不等于实际持仓无风险。",
             "- 硬底线与收盘保护位使用图表同一复权尺度；实际首仓价格、可卖数量和既往减仓须另核。", "",
             "## 边界", "- 生命周期主状态、子形态和风险叠加分开表达。",
             "- S2/S3为当前引擎形态代理，尚非完整V3策略验证；观察窗口阈值待校准。",
             "- D1经营证据、D5独立注意力证据尚未绑定；不推断预期差或潜在收益。",
             "- 图形入口：python mainwave_visual_app.py（固定端口8068）。"]
    if errors:
        lines += ["", "## 未完成标的", *[f"- {e['symbol']}: {e['error']}" for e in errors]]
    (output / "analysis_board.md").write_text("\n".join(lines), encoding="utf-8")
    print(f"[analysis_daily] {date} analyzed={len(records)}/{len(candidates)} "
          f"failed={len(errors)} advice={summary['advice_counts']} -> {output / 'analysis_board.md'}", flush=True)
    print(f"[analysis_daily] sell_policy={AC.XP.VERSION} reference_alerts={len(exit_alerts)} "
          f"states={summary['sell_reference_counts']} (reference only, no orders)", flush=True)
    print(f"[analysis_daily] price_volume={PVC.VERSION} states={summary['price_volume_counts']} (shadow only)", flush=True)
    return payload


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--date", required=True)
    result = run(parser.parse_args().date)
    raise SystemExit(1 if result["errors"] else 0)
